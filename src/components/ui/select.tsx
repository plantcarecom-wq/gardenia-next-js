/**
 * Base UI's <Select.Value> only auto-resolves a selected value's display
 * label when an `items` map is passed to <Select.Root> — otherwise it
 * renders the raw `value` (e.g. a Mongo id) verbatim. None of this app's
 * ~15 Select call sites pass `items` (they render <SelectItem> children
 * directly, per-item), so every one of them showed raw ids once a value was
 * selected.
 *
 * Rather than retrofit `items` onto every call site, this wraps Root and
 * walks its `children` JSX synchronously during render to build a
 * value -> label lookup, which SelectValue then uses as its default
 * `children` resolver. This must be synchronous (not effect/mount-based):
 * an effect-based "SelectItem registers itself on mount" approach looked
 * simpler but silently failed for a value that's selected by default before
 * the popup has ever been opened — SelectValue reads the map during render,
 * one render before the registering effect has had a chance to run, so it
 * falls back to the raw value on that first paint. Walking the already
 *-available `children` prop has no such timing gap.
 */
const SelectLabelsContext = React.createContext<Map<unknown, React.ReactNode>>(new Map())

function collectItemLabels(children: React.ReactNode, map: Map<unknown, React.ReactNode>) {
  React.Children.forEach(children, (child) => {
    if (!React.isValidElement(child)) return
    const childProps = child.props as { value?: unknown; children?: React.ReactNode }
    if (child.type === SelectItem) {
      if (childProps.value !== undefined) map.set(childProps.value, childProps.children)
      return
    }
    if (childProps.children) collectItemLabels(childProps.children, map)
  })
}

function Select<Value, Multiple extends boolean | undefined = false>(
  props: SelectPrimitive.Root.Props<Value, Multiple>
) {
  const labels = React.useMemo(() => {
    const map = new Map<unknown, React.ReactNode>()
    collectItemLabels(props.children, map)
    return map
  }, [props.children])

  return (
    <SelectLabelsContext.Provider value={labels}>
      <SelectPrimitive.Root {...props} />
    </SelectLabelsContext.Provider>
  )
}

